#include <iostream>
#include <clocale>

using namespace std;

//С клавиатуры заполняются 2 массива целых чисел(по 5 элементов в каждом).
//Необходимо реализовать программу, которая позволила бы(без введения дополнительных
//массивов) перераспределить числа в массивах таким образом, чтобы в одном массиве
//остались только положительные, а во втором – только отрицательные числа.

int main()
{
    setlocale(LC_ALL, "");
    int A[10] = { 0 };
    int B[10] = { 0 };

    cout << "Введите 5 чисел массива A:" << endl;
    for (int i = 0; i < 5; i++) {
        cin >> A[i];
    }

    cout << "Введите 5 чисел массива B:" << endl;
    for (int i = 0; i < 5; i++) {
        cin >> B[i];
    }

    //Сортировка массива A, чтобы в нем сначал были положительные, потом отрицательные, а в конце 0
    //Это нужно, чтобы соблюдалось условие: приоритет при размещении должны иметь числа, исходно содержащиеся в массивах
    //В массиве A сначла будет идти все изначалтные положительные числа, а после размещение новые из массива B
    // Шаг 1: положительные — в начало
    for (int i = 0; i < 9; i++) {
        for (int j = 0; j < 9 - i; j++) {
            if (A[j] <= 0 && A[j + 1] > 0) {
                int temp = A[j];
                A[j] = A[j + 1];
                A[j + 1] = temp;
            }
        }
    }
    // Шаг 2: нули — в конец
    for (int i = 0; i < 9; i++) {
        for (int j = 0; j < 9 - i; j++) {
            if (A[j] == 0 && A[j + 1] != 0) {
                int temp = A[j];
                A[j] = A[j + 1];
                A[j + 1] = temp;
            }
        }
    }

    //Сортировка массива B, чтобы в нем сначал были отрицательные, потом пложительные, а в конце 0
    // Шаг 1: отрицательные — в начало
    for (int i = 0; i < 9; i++) {
        for (int j = 0; j < 9 - i; j++) {
            if (B[j] >= 0 && B[j + 1] < 0) {
                int temp = B[j];
                B[j] = B[j + 1];
                B[j + 1] = temp;
            }
        }
    }
    // Шаг 2: нули — в конец
    for (int i = 0; i < 9; i++) {
        for (int j = 0; j < 9 - i; j++) {
            if (B[j] == 0 && B[j + 1] != 0) {
                int temp = B[j];
                B[j] = B[j + 1];
                B[j + 1] = temp;
            }
        }
    }

    //Здесь сначала пробегаемся по массиву A, находим отрицательный элемент и перемещаем его в массив B
    for (int i = 0; i < 5; i++) {
        if (A[i] < 0) {
            for (int j = 0; j < 10; j++) {
                if (B[j] >= 0) {
                    int temp = A[i];
                    A[i] = B[j];
                    B[j] = temp;
                    break;
                }
            }
        }
    }

    //Здесь делаем проход по массиву B, находим положительные элементы и перемещаем их в массив A
    for (int j = 0; j < 5; j++) {
        if (B[j] > 0) {
            for (int i = 0; i < 10; i++) {
                if (A[i] <= 0) {
                    int temp = B[j];
                    B[j] = A[i];
                    A[i] = temp;
                    break;
                }
            }
        }
    }

    //Выводим массивы A и B в строчку
    cout << "Новый массив A:" << endl;
    for (int i = 0; i < 10; i++) {
        cout << A[i] << " ";
    }

    cout << "\nНовый массив B:" << endl;
    for (int j = 0; j < 10; j++) {
        cout << B[j] << " ";
    }
}

